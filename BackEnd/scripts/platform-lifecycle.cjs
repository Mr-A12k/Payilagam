async function request(who, method, route, body, expected = 200, binary = false) {
  const response = await fetch(base + route, { method, headers: { ...(tokens[who] ? { Authorization: `Bearer ${tokens[who]}` } : {}), ...(body && !(body instanceof FormData) ? { 'Content-Type': 'application/json' } : {}) }, body: body ? body instanceof FormData ? body : JSON.stringify(body) : undefined, signal: AbortSignal.timeout(15000) });
  const result = binary ? await response.arrayBuffer() : await response.json();
  assert.equal(response.status, expected, `${method} ${route}: ${result.message || ''}`);
  passed++;
  console.log(`PASS ${method} ${route} (${expected})`);
  return binary ? result : result.data;
}
